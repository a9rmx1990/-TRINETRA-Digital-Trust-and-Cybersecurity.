"""SQLite and Postgres transaction boundaries for the sandbox ledger."""

import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path


SQLITE_AUDIT = """
CREATE TRIGGER IF NOT EXISTS soc_audit_no_update BEFORE UPDATE ON soc_tool_audit
BEGIN SELECT RAISE(ABORT, 'SOC tool audit is append-only'); END;
CREATE TRIGGER IF NOT EXISTS soc_audit_no_delete BEFORE DELETE ON soc_tool_audit
BEGIN SELECT RAISE(ABORT, 'SOC tool audit is append-only'); END;
"""
JSON_PATH = re.compile(r"json_extract\(([\w.]+), '\$\.([a-z_]+)'\)")
IDENTITY = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"


def postgres_sql(query):
    query = JSON_PATH.sub(r"jsonb_extract_path_text(CAST(\1 AS jsonb), '\2')", query)
    return query.replace("MAX(0, ? - created)", "GREATEST(0, ? - created)").replace("?", "%s")


class PostgresTransaction:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, parameters=()):
        if query.strip() == "BEGIN":
            return None
        return self.connection.execute(postgres_sql(query), parameters or None)


class Database:
    def __init__(self, path, url, schema):
        self.url = url
        if url:
            with self.tx(write=True) as db:
                for query in schema.replace("INTEGER PRIMARY KEY AUTOINCREMENT", IDENTITY).split(";"):
                    if query.strip():
                        db.execute(query)
                db.execute("""
                    CREATE OR REPLACE FUNCTION protect_soc_audit() RETURNS trigger AS $$
                    BEGIN RAISE EXCEPTION 'SOC tool audit is append-only'; END;
                    $$ LANGUAGE plpgsql
                """)
                db.execute("""
                    CREATE OR REPLACE TRIGGER soc_audit_append_only BEFORE UPDATE OR DELETE ON soc_tool_audit
                    FOR EACH ROW EXECUTE FUNCTION protect_soc_audit()
                """)
        else:
            self.path = Path(path)
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.tx() as db:
                db.execute("PRAGMA journal_mode=WAL")
                db.executescript(schema + SQLITE_AUDIT)

    @contextmanager
    def tx(self, write=False):
        if self.url:
            import psycopg
            from psycopg.rows import dict_row

            with psycopg.connect(self.url, row_factory=dict_row, connect_timeout=3) as connection:
                if write:
                    # Match the serial SQLite write boundary across all sandbox workers.
                    connection.execute("SELECT pg_advisory_xact_lock(184372195)")
                else:
                    connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY")
                yield PostgresTransaction(connection)
            return

        db = sqlite3.connect(self.path, timeout=3)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys=ON")
        try:
            if write:
                db.execute("BEGIN IMMEDIATE")
            yield db
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()
